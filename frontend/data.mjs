export const PRIORITIES = ["high", "medium", "low"];
export const SENTIMENTS = ["positive", "neutral", "negative"];

export function normalizeAppInput(value, country = null) {
  const input = value.trim();
  if (/^[0-9]+$/.test(input) && !/^0+$/.test(input))
    return { app_id: input, country: country || "us" };
  let url;
  try {
    url = new URL(input);
  } catch {
    throw new Error("Enter a numeric app ID or an App Store URL.");
  }
  const match = url.pathname.match(/\/id([0-9]+)(?:\/|$)/);
  if (
    url.protocol !== "https:" ||
    !["apps.apple.com", "itunes.apple.com"].includes(url.hostname) ||
    !match ||
    /^0+$/.test(match[1])
  )
    throw new Error("Enter a valid Apple App Store URL containing an app ID.");
  const region = url.pathname.split("/")[1];
  return {
    app_id: match[1],
    country:
      country || (/^[a-z]{2}$/i.test(region) ? region.toLowerCase() : "us"),
  };
}

export function dashboardSources(response) {
  if (
    !response?.collection ||
    !response.metrics?.sentiment ||
    !Array.isArray(response.insights?.issues) ||
    !Array.isArray(response.insights?.recommendations) ||
    !Array.isArray(response.reviews)
  )
    throw new Error("The API returned an incomplete analysis report.");
  const metadata = {
    ...response.collection,
    ...response.app,
    app_name: response.app.name,
  };
  const grouped = Object.fromEntries(
    PRIORITIES.map((priority) => [priority, { repeated: [], single: [] }]),
  );
  const recommendations = new Map(
    response.insights.recommendations.map((item) => [
      item.category,
      item.action,
    ]),
  );
  for (const issue of response.insights.issues) {
    if (!grouped[issue.priority] || !Array.isArray(issue.evidence_ids))
      throw new Error("The API returned an invalid issue.");
    grouped[issue.priority][
      issue.evidence_ids.length > 1 ? "repeated" : "single"
    ].push({ ...issue, action: recommendations.get(issue.category) });
  }
  return {
    metrics: {
      ...response.metrics,
      metadata,
      sentiments: response.metrics.sentiment,
    },
    report: {
      metadata,
      summary: {
        total_reviews: response.metrics.total_reviews,
        sentiments: response.metrics.sentiment.counts,
      },
      insights: grouped,
    },
    reviews: { metadata, reviews: response.reviews },
  };
}

export function escapeHTML(value) {
  return String(value).replace(
    /[&<>"']/g,
    (character) =>
      ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[
        character
      ],
  );
}

function count(value, name) {
  if (!Number.isSafeInteger(value) || value < 0)
    throw new Error(`${name} must be a nonnegative integer.`);
  return value;
}

export function prepareDashboard(metrics, report, reviews = null) {
  if (!metrics || !report || !Array.isArray(metrics.issues?.items))
    throw new Error(
      "Choose metrics and insight JSON files generated by this project.",
    );
  const total = count(metrics.total_reviews, "Total reviews");
  const stars = [1, 2, 3, 4, 5].map((star) => ({
    star,
    count: count(metrics.ratings?.counts?.[star], `${star}-star count`),
  }));
  const rated = count(metrics.ratings.rated_reviews, "Rated reviews");
  const classified = count(
    metrics.sentiments?.classified_reviews,
    "Classified reviews",
  );
  const sentiments = SENTIMENTS.map((label) => ({
    label,
    count: count(metrics.sentiments.counts?.[label], `${label} count`),
  }));
  if (
    stars.reduce((sum, item) => sum + item.count, 0) !== rated ||
    sentiments.reduce((sum, item) => sum + item.count, 0) !== classified ||
    rated > total ||
    classified > total
  )
    throw new Error("Review totals and distribution counts do not match.");
  const average = rated
    ? stars.reduce((sum, item) => sum + item.star * item.count, 0) / rated
    : null;
  if (
    (average === null && metrics.ratings.average !== null) ||
    (average !== null &&
      (!Number.isFinite(metrics.ratings.average) ||
        Math.abs(average - metrics.ratings.average) > 1e-8))
  )
    throw new Error("Average rating does not match the rating distribution.");
  for (const key of ["app_id", "country"]) {
    if (
      metrics.metadata?.[key] != null &&
      report.metadata?.[key] != null &&
      metrics.metadata[key] !== report.metadata[key]
    )
      throw new Error("These files describe different apps or countries.");
  }
  if (
    report.summary?.total_reviews !== total ||
    sentiments.some(
      (item) => report.summary?.sentiments?.[item.label] !== item.count,
    )
  )
    throw new Error("Metrics and insights describe different review samples.");
  const actions = new Map();
  for (const priority of PRIORITIES) {
    for (const recurrence of ["repeated", "single"]) {
      const items = report.insights?.[priority]?.[recurrence];
      if (!Array.isArray(items))
        throw new Error("The insights file is missing priority groups.");
      for (const issue of items) {
        if (
          typeof issue.category !== "string" ||
          typeof issue.action !== "string" ||
          !Array.isArray(issue.evidence_ids) ||
          actions.has(issue.category)
        )
          throw new Error(
            "The insights file contains invalid or duplicate issues.",
          );
        actions.set(issue.category, { ...issue, priority });
      }
    }
  }
  const covered = new Set();
  const categories = new Set();
  const negative = sentiments.find((item) => item.label === "negative").count;
  const issues = metrics.issues.items
    .map((issue) => {
      const action = actions.get(issue.category);
      const ids = issue.evidence_ids;
      if (
        !action ||
        categories.has(issue.category) ||
        action.priority !== issue.priority ||
        !Array.isArray(ids) ||
        !ids.length ||
        !ids.every((id) => typeof id === "string") ||
        new Set(ids).size !== ids.length ||
        count(issue.frequency, "Issue frequency") !== ids.length ||
        ids.length > negative ||
        new Set(action.evidence_ids).size !== ids.length ||
        !ids.every((id) => action.evidence_ids.includes(id))
      )
        throw new Error(
          "Issue evidence differs between metrics and insights. Recalculate metrics for this report.",
        );
      categories.add(issue.category);
      ids.forEach((id) => covered.add(id));
      return {
        ...issue,
        action: action.action,
        fraction: negative ? ids.length / negative : null,
      };
    })
    .sort(
      (a, b) =>
        PRIORITIES.indexOf(a.priority) - PRIORITIES.indexOf(b.priority) ||
        b.frequency - a.frequency ||
        a.category.localeCompare(b.category),
    );
  if (
    actions.size !== issues.length ||
    covered.size > negative ||
    metrics.issues.covered_negative_reviews !== covered.size ||
    metrics.issues.negative_reviews !== negative
  )
    throw new Error("Issue coverage does not match the evidence IDs.");
  const reviewMap = new Map();
  if (reviews !== null) {
    if (!Array.isArray(reviews.reviews) || reviews.reviews.length !== total)
      throw new Error("The review file does not match this sample.");
    for (const review of reviews.reviews) {
      const label =
        typeof review.sentiment === "string"
          ? review.sentiment
          : review.sentiment?.label;
      if (
        typeof review.id !== "string" ||
        reviewMap.has(review.id) ||
        typeof review.text !== "string"
      )
        throw new Error("Review records have missing text or duplicate IDs.");
      reviewMap.set(review.id, { ...review, label });
    }
    for (const id of covered)
      if (reviewMap.get(id)?.label !== "negative")
        throw new Error(
          "Issue evidence must reference negative reviews in this sample.",
        );
    for (const item of sentiments)
      if (
        [...reviewMap.values()].filter((review) => review.label === item.label)
          .length !== item.count
      )
        throw new Error("The review file has different sentiment counts.");
    for (const item of stars)
      if (
        [...reviewMap.values()].filter((review) => review.rating === item.star)
          .length !== item.count
      )
        throw new Error("The review file has different rating counts.");
  }
  return {
    total,
    stars,
    rated,
    average,
    classified,
    sentiments,
    negative,
    issues,
    covered: covered.size,
    coverage: negative ? covered.size / negative : null,
    reviewMap,
    metadata: metrics.metadata || {},
  };
}

export function filterIssues(issues, priority = "all", recurrence = "all") {
  return issues.filter(
    (issue) =>
      (priority === "all" || issue.priority === priority) &&
      (recurrence === "all" ||
        (recurrence === "repeated"
          ? issue.frequency > 1
          : issue.frequency === 1)),
  );
}
